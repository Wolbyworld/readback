import assert from "node:assert/strict";
import test from "node:test";
import { browser, runBrowserHarness } from "./browser-harness.mjs";
import { frameHarness, panelHarness } from "./panel-harness.mjs";

test("repeat uses the saved quiz; new questions make a fresh request and preserve results on failure or cancel", { skip: !browser }, async () => {
  const html = await panelHarness(`
    state.answers = [0,1,0]; state.index = 2; renderResults(); await tick();
    const original = state.quiz;
    $('#retryButton').click(); await tick();
    results.repeat = { same:state.quiz === original, answers:[...state.answers], index:state.index, requests:calls.filter(x => x.type === 'READBACK_GENERATE_QUIZ').length };
    state.answers = [0,1,0]; state.index = 2; renderResults(); await tick();
    state.settings = { questionCount:10,optionCount:5,level:'challenge' };
    generateResponse = async () => ({ ok:false,error:{code:'OPENAI_NETWORK',message:'Connection failed.'} });
    $('#newQuizButton').click(); await tick();
    results.failed = { same:state.quiz === original, answers:[...state.answers], screen:state.screen, message:$('#errorMessage').textContent, saved:storedRecords[tabStateKey(tab.id)].quiz.title };
    results.request = calls.find(x => x.type === 'READBACK_GENERATE_QUIZ');
    $('#errorHomeButton').click(); await tick();
    results.restored = state.screen;
    let finish;
    generateResponse = () => new Promise(resolve => { finish = resolve; });
    $('#newQuizButton').click(); await tick();
    results.loading = state.screen;
    $('#cancelButton').click(); await tick();
    finish({ ok:true,payload:{quiz:makeQuiz('Late')} }); await tick();
    results.cancelled = { same:state.quiz === original,screen:state.screen,answers:[...state.answers] };
    generateResponse = async () => ({ ok:true,payload:{quiz:makeQuiz('Fresh')} });
    $('#newQuizButton').click(); await tick();
    results.success = { different:state.quiz !== original,prompt:state.quiz.questions[0].prompt,screen:state.screen,index:state.index,answers:[...state.answers],settings:state.quizSettings };
    state.answers = [0,0,0]; state.index = 2; renderResults(); await tick();
    const fresh = state.quiz;
    const count = calls.filter(x => x.type === 'READBACK_GENERATE_QUIZ').length;
    extractedUrl = 'https://example.com/other';
    $('#newQuizButton').click(); await tick();
    results.changed = { same:state.quiz === fresh,requests:calls.filter(x => x.type === 'READBACK_GENERATE_QUIZ').length-count,message:$('#errorMessage').textContent };
  `);
  const [{ results: r }] = await runBrowserHarness(frameHarness(html, [[320,640]]));
  assert.equal(r.error, undefined, r.error);
  assert.deepEqual(r.repeat, { same:true,answers:[null,null,null],index:0,requests:0 });
  assert.equal(r.failed.same,true);
  assert.deepEqual(r.failed.answers,[0,1,0]);
  assert.equal(r.failed.screen,'error');
  assert.equal(r.failed.saved,'The Cognitive Revolution');
  assert.equal(r.request.page.url,'https://example.com/source');
  assert.deepEqual(r.request.settings,{questionCount:3,optionCount:3,level:'apply'});
  assert.equal(r.request.previousQuestions.length,3);
  assert.equal(r.restored,'results');
  assert.equal(r.loading,'loading');
  assert.deepEqual(r.cancelled,{same:true,screen:'results',answers:[0,1,0]});
  assert.equal(r.success.different,true);
  assert.match(r.success.prompt,/^Fresh/);
  assert.equal(r.success.screen,'quiz');
  assert.deepEqual(r.success.answers,[null,null,null]);
  assert.equal(r.success.index,0);
  assert.deepEqual(r.success.settings,r.request.settings);
  assert.equal(r.changed.same,true);
  assert.equal(r.changed.requests,0);
  assert.match(r.changed.message,/source page has changed/);
});
